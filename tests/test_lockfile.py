"""依赖锁文件（requirements.lock）生成与校验."""

from __future__ import annotations

import hashlib
from pathlib import Path

import pytest

from fspack.exceptions import DependencyError
from fspack.packaging.lockfile import (
    LOCK_FILE_NAME,
    read_requirements_lock,
    verify_wheels_against_lock,
    write_requirements_lock,
)


def _wheel(directory: Path, name: str, data: bytes) -> Path:
    path = directory / name
    path.write_bytes(data)
    return path


def _write_lock(tmp_path: Path, wheels: list[Path]) -> Path:
    return write_requirements_lock(
        tmp_path / LOCK_FILE_NAME,
        wheels,
        py_version="3.11.9",
        platform="windows",
        index="https://idx/simple",
    )


def test_write_lock_sorted_and_hashed(tmp_path: Path) -> None:
    """锁文件按包名排序，每行 name==version + wheel sha256，头部含构建目标."""
    wheels = [
        _wheel(tmp_path, "pillow-10.4.0-cp311-cp311-win_amd64.whl", b"pillow"),
        _wheel(tmp_path, "numpy-1.26.4-cp311-cp311-win_amd64.whl", b"numpy"),
    ]
    path = _write_lock(tmp_path, wheels)
    text = path.read_text(encoding="utf-8")
    assert "# python=3.11.9" in text
    assert "# platform=windows" in text
    assert "# index=https://idx/simple" in text
    lines = [line for line in text.splitlines() if line and not line.startswith("#")]
    assert lines == [
        f"numpy==1.26.4 --hash=sha256:{hashlib.sha256(b'numpy').hexdigest()}",
        f"pillow==10.4.0 --hash=sha256:{hashlib.sha256(b'pillow').hexdigest()}",
    ]
    # 无时间戳/随机内容：同输入重复生成结果一致
    second = _write_lock(tmp_path, wheels).read_text(encoding="utf-8")
    assert second == text


def test_write_lock_merges_hashes_per_version(tmp_path: Path) -> None:
    """同一 name==version 的多个平台 wheel 合并到一行多个 --hash，排序去重."""
    wheels = [
        _wheel(tmp_path, "numpy-1.26.4-cp310-cp310-manylinux_2_17_x86_64.whl", b"linux"),
        _wheel(tmp_path, "numpy-1.26.4-cp311-cp311-win_amd64.whl", b"windows"),
    ]
    line = next(
        line
        for line in _write_lock(tmp_path, wheels).read_text(encoding="utf-8").splitlines()
        if line.startswith("numpy==")
    )
    hashes = sorted([hashlib.sha256(b"linux").hexdigest(), hashlib.sha256(b"windows").hexdigest()])
    assert line == f"numpy==1.26.4 --hash=sha256:{hashes[0]} --hash=sha256:{hashes[1]}"


def test_write_lock_unparsable_wheel_raises(tmp_path: Path) -> None:
    """无法解析文件名的 wheel 无法写锁文件."""
    bad = _wheel(tmp_path, "not-a-wheel.txt", b"x")
    with pytest.raises(DependencyError, match="无法从 wheel 文件名解析"):
        _write_lock(tmp_path, [bad])


def test_read_lock_roundtrip(tmp_path: Path) -> None:
    """写入后可读回：requirements 与 hashes 与写入内容一致."""
    wheels = [
        _wheel(tmp_path, "numpy-1.26.4-cp311-cp311-win_amd64.whl", b"numpy"),
        _wheel(tmp_path, "pillow-10.4.0-cp311-cp311-win_amd64.whl", b"pillow"),
    ]
    lock = read_requirements_lock(_write_lock(tmp_path, wheels))
    assert lock.requirements == ("numpy==1.26.4", "pillow==10.4.0")
    assert lock.hashes["numpy"] == frozenset({hashlib.sha256(b"numpy").hexdigest()})
    assert lock.metadata == {"python": "3.11.9", "platform": "windows", "index": "https://idx/simple"}


def test_read_lock_missing_file_raises(tmp_path: Path) -> None:
    """--frozen 时锁文件缺失直接报错，提示生成方式."""
    with pytest.raises(DependencyError, match="--lock"):
        read_requirements_lock(tmp_path / LOCK_FILE_NAME)


def test_read_lock_invalid_line_raises(tmp_path: Path) -> None:
    """非注释行不符合格式时报错（含行号）."""
    path = tmp_path / LOCK_FILE_NAME
    path.write_text("numpy>=1.0\n", encoding="utf-8")
    with pytest.raises(DependencyError, match="第 1 行"):
        read_requirements_lock(path)


def test_read_lock_empty_raises(tmp_path: Path) -> None:
    """只有注释没有依赖行视为无效锁文件."""
    path = tmp_path / LOCK_FILE_NAME
    path.write_text("# Generated by fspack --lock; do not edit.\n", encoding="utf-8")
    with pytest.raises(DependencyError, match="不含任何依赖行"):
        read_requirements_lock(path)


def test_verify_lock_ok(tmp_path: Path) -> None:
    """wheel 包名与 sha256 均命中锁文件时校验通过."""
    wheels = [_wheel(tmp_path, "numpy-1.26.4-cp311-cp311-win_amd64.whl", b"numpy")]
    lock = read_requirements_lock(_write_lock(tmp_path, wheels))
    verify_wheels_against_lock(wheels, lock)


def test_verify_lock_unknown_package_raises(tmp_path: Path) -> None:
    """下载结果出现锁文件未包含的依赖时报错."""
    lock_wheel = _wheel(tmp_path, "numpy-1.26.4-cp311-cp311-win_amd64.whl", b"numpy")
    lock = read_requirements_lock(_write_lock(tmp_path, [lock_wheel]))
    extra = _wheel(tmp_path, "pillow-10.4.0-cp311-cp311-win_amd64.whl", b"pillow")
    with pytest.raises(DependencyError, match=r"不在 requirements\.lock 中"):
        verify_wheels_against_lock([lock_wheel, extra], lock)


def test_verify_lock_hash_mismatch_raises(tmp_path: Path) -> None:
    """wheel 内容与锁文件 sha256 不符时报错（不静默复用）。"""
    wheel = _wheel(tmp_path, "numpy-1.26.4-cp311-cp311-win_amd64.whl", b"numpy")
    lock = read_requirements_lock(_write_lock(tmp_path, [wheel]))
    tampered = _wheel(tmp_path, "numpy-1.26.4-cp311-cp311-win_amd64.whl", b"tampered")
    with pytest.raises(DependencyError, match=r"sha256 与 requirements\.lock 不符"):
        verify_wheels_against_lock([tampered], lock)


def test_verify_lock_missing_locked_dependency_raises(tmp_path: Path) -> None:
    """锁文件中的依赖未出现在下载结果（新增/变更依赖后忘记重新生成锁）时报错."""
    wheels = [
        _wheel(tmp_path, "numpy-1.26.4-cp311-cp311-win_amd64.whl", b"numpy"),
        _wheel(tmp_path, "pillow-10.4.0-cp311-cp311-win_amd64.whl", b"pillow"),
    ]
    lock = read_requirements_lock(_write_lock(tmp_path, wheels))
    with pytest.raises(DependencyError, match="未出现在本次下载结果: pillow"):
        verify_wheels_against_lock(wheels[:1], lock)
